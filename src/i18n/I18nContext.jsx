const I18nContext = createContext(null);

function interpolate(template, values) {
  if (typeof template !== 'string') return template;
  if (!values) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (_, key) => values[key] ?? '');
}

export function I18nProvider({ children }) {
  const [language, setLanguageState] = useState(() => localStorage.getItem(STORAGE_KEY) || defaultLanguage);

  useEffect(() => {
    document.documentElement.lang = language;
    localStorage.setItem(STORAGE_KEY, language);
  }, [language]);

  const setLanguage = useCallback((next) => {
    setLanguageState(dictionaries[next] ? next : defaultLanguage);
  }, []);

  const t = useCallback(
    (key, values) => (key ? interpolate(dictionaries[language]?.[key] ?? dictionaries.ru[key] ?? key, values) : ''),
    [language],
  );

  const value = useMemo(() => ({ language, languages, setLanguage, t }), [language, setLanguage, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function translateNow(key, values) {
  const language = localStorage.getItem(STORAGE_KEY) || defaultLanguage;
  return interpolate(dictionaries[language]?.[key] ?? dictionaries.ru[key] ?? key, values);
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error('useI18n must be used inside I18nProvider');
  return context;
}
